/// لون من الكتالوج بحسب الوضع، أو null إن لم يكن معروفاً.
Color? layoutColor(BuildContext context, String key) {
  final c = layoutColors[key];
  if (c == null) return null;
  return Theme.of(context).brightness == Brightness.dark ? c.$3 : c.$2;
}
